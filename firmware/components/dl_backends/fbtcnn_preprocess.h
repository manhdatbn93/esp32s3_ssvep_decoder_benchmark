/*
 * FBtCNN filter-bank preprocessing: raw EEG → 4-band filtered tensor.
 *
 * The FBtCNN model was trained with a scipy Butterworth filter bank
 * applied outside the network (src/models/fbtcnn.py → _filter_bank).
 * The TFLite model is the *post-filter-bank* network, so this module
 * replicates the host-side filtering on the ESP32-S3.
 *
 * Filter bank (from src/models/fbtcnn.py):
 *   Band 0:  3–14 Hz   6th-order Butterworth bandpass
 *   Band 1:  9–26 Hz   6th-order Butterworth bandpass
 *   Band 2: 14–38 Hz   6th-order Butterworth bandpass
 *   Band 3: 19–50 Hz   6th-order Butterworth bandpass
 *
 * Each band: scipy.signal.filtfilt (zero-phase, odd extension).
 * Reuses the existing sosfilt_mcu from the common component.
 *
 * SOS coefficients generated by export/gen_fbtcnn_filter_header.py
 * and stored in fbtcnn_filter_generated.h.
 */
#ifndef FBTCNN_PREPROCESS_H
#define FBTCNN_PREPROCESS_H

#define FBTCNN_INPUT_T      512
#define FBTCNN_INPUT_C      8
#define FBTCNN_NUM_BANDS    4
#define FBTCNN_FEATURE_LEN  16384  /* INPUT_C * INPUT_T * NUM_BANDS */

/*
 * Apply the 4-band Butterworth filter bank to raw EEG.
 *
 * input_tc : 4096 floats, [time=512, channel=8] row-major.
 * output   : 16384 floats, NHWC [1, C=8, T=512, B=4] row-major.
 *            output[c * 512 * 4 + t * 4 + b] = filtered sample.
 */
void fbtcnn_preprocess(const float *input_tc, float *output);

#endif /* FBTCNN_PREPROCESS_H */
